/**
 * THE SERVICE MENU — one record per routable service variant.
 *
 * GENERATED. Do not hand-edit: run `Kiosk v3/build_service_menu.py`, which joins the
 * decision-tree routing in the old `data.ts` CSV to the money in
 * `Kiosk v3/M2M_SERVICES_AND_FEES_CORRECTED_2026-08-05.xlsx` — the sole authority for
 * every price, turnaround and insured value.
 *
 * ⚠️ CUSTOMER PRICES ONLY. `price.employee`, `price.owner` and `cost` are typed here but
 * are ALWAYS null in this file, because everything in this file ships to every kiosk and
 * anything in the bundle is public. Role pricing is resolved server-side after login —
 * see Phase 4 of the brief. The real employee/owner figures live outside this repo, in
 * `Kiosk v3/M2M_SERVICE_MENU_ROLE_PRICING.json`.
 *
 * `active: false` replaces the hardcoded PSA-Value suppression that used to sit inside
 * the CSV parser, marked "temporarily", still live six weeks later. Retiring a service is
 * now a data change that shows up in a diff.
 *
 * ADDING A NEW GRADING COMPANY is a data change: append records with their six question
 * values and re-run the generator. MBA proved it on 2026-08-07 — four routing rows, four
 * ALIAS entries, no code change at all. A service that is priced in the sheet but has no
 * routing yet is marked HOLD — NOT YET LIVE and stays out of the menu until it has one;
 * do not invent routing to get it on screen.
 */

/** The six decision-tree answers, in order. `null` = not routable yet. */
export type QuestionPath = [string, string, string, string, string, string];

export interface ServicePrice {
  /** The only tier that may ship to a kiosk. */
  customer: number;
  /** Always null in the bundle. Resolved server-side after a role login. */
  employee: number | null;
  /** Always null in the bundle. Resolved server-side after a role login. */
  owner: number | null;
}

export interface ServiceRecord {
  category: string;
  name: string;
  /** null when the sheet carries a service the decision tree cannot yet reach. */
  questions: QuestionPath | null;
  price: ServicePrice;
  /** What M2M pays the grader. Never shipped — always null here. */
  cost: number | null;
  businessDays: number;
  maxInsuredValue: string;
  /** false = retired/suspended. Kept as history; filtered out of the flow. */
  active: boolean;
  status: string;
  /**
   * The price is a STARTING price, not the price. Memorabilia authentication is costed
   * per item after assessment, so the figure on screen is a minimum and the customer
   * must be told that before they add it to a cart.
   */
  priceIsMinimum: boolean;
  /**
   * A flat upcharge, per card, for an oversized card — or null if the service does not
   * accept one. This is a MODIFIER, not a separate service: the pricing sheet lists
   * "BGS Express — Oversized" as its own row, but making those menu entries would double
   * every BGS tier on screen and would not follow BGS Base and Standard back off
   * suspension. The figure is measured from the sheet, not typed here.
   */
  oversizedSurcharge: number | null;
}

